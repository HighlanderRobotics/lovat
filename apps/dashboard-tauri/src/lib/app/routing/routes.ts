export type RouteName = keyof typeof definitions;
export type FeatureName = (typeof definitions)[RouteName]['feature'];
export type RouteDefinition = Omit<
	RouteDefinitionBase,
	'feature' | 'parent' | 'viewOf'
> & { feature: FeatureName; parent: RouteName; viewOf?: RouteName };
export const routes: Record<RouteName, RouteDefinition> = definitions;

export function isRouteName(value: string): value is RouteName {
	return Object.hasOwn(routes, value);
}
export function routePath(name: RouteName): string {
	return routes[name].path;
}
export const routeNames = Object.keys(routes) as RouteName[];
export function routeForPath(path: string): RouteName | undefined {
	return routeNames.find(
		(name) => routes[name].path === path.replace(/\/$/, ''),
	);
}
export function parentRoute(name: RouteName): RouteName {
	return routes[name].parent;
}
export function selectionScope(name: RouteName): string {
	return routes[name].selectionScope ?? name;
}
export function viewBase(name: RouteName): RouteName {
	return routes[name].viewOf ?? name;
}
export function isViewChange(from: RouteName, to: RouteName): boolean {
	return viewBase(from) === viewBase(to);
}
